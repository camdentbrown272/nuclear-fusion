class Material:
    def __init__(self, name, rho, comp, by='atoms', I=None, x0_ref=None,
                 note=''):
        """comp: dict element->count (by='atoms') or mass fraction (by='mass')."""
        self.name, self.rho, self.note = name, rho, note
        els = list(comp)
        if by == 'atoms':
            m = np.array([comp[e] * ELEMENTS[e][1] for e in els])
            w = m / m.sum()
        else:
            w = np.array([comp[e] for e in els], float)
            w = w / w.sum()
        self.els = els
        self.w = w
        self.Z = np.array([ELEMENTS[e][0] for e in els], float)
        self.A = np.array([ELEMENTS[e][1] for e in els], float)
        self.ZA = float(np.sum(w * self.Z / self.A))           # <Z/A> [mol/g]
        if I is None:   # Bragg additivity of ln I weighted by electrons
            Ie = np.array([ELEMENTS[e][2] for e in els])
            I = float(np.exp(np.sum(w * self.Z / self.A * np.log(Ie)) / self.ZA))
        self.I = I * 1e-6                                        # [MeV]
        self.x0_ref = x0_ref
        self._density_params()
        self.X0 = self._radiation_length()                       # [g/cm2]
        self.ne = self.ZA * NA * rho if rho > 0 else 0.0          # e-/cm3

    # Sternheimer & Peierls (1971) general formula for condensed media
    def _density_params(self):
        if self.rho <= 0:
            self.dens = None
            return
        hwp = 28.816e-6 * np.sqrt(self.rho * self.ZA)             # MeV
        C = 2.0 * np.log(self.I / hwp) + 1.0
        gas = self.rho < 0.01
        if gas:
            x0 = 1.6 if C < 10.0 else 0.326 * C - 1.7
            x1 = 4.0
        elif self.I < 100e-6:
            x1 = 2.0
            x0 = 0.2 if C < 3.681 else 0.326 * C - 1.0
        else:
            x1 = 3.0
            x0 = 0.2 if C < 5.215 else 0.326 * C - 1.5
        m = 3.0
        a = (C - 2 * LN10 * x0) / (x1 - x0) ** m
        self.dens = (C, x0, x1, a, m)

    def delta(self, x):
        C, x0, x1, a, m = self.dens
        x = np.asarray(x, float)
        d = np.where(x >= x1, 2 * LN10 * x - C,
                     np.where(x >= x0, 2 * LN10 * x - C + a * np.clip(x1 - x, 0, None) ** m, 0.0))
        return d

    def _radiation_length(self):
        inv = 0.0
        for w, Z, A in zip(self.w, self.Z, self.A):
            a2 = (ALPHA * Z) ** 2
            f = a2 * (1 / (1 + a2) + 0.20206 - 0.0369 * a2 + 0.0083 * a2 ** 2 - 0.002 * a2 ** 3)
            Lr = {1: 5.31, 2: 4.79, 3: 4.74, 4: 4.71}.get(int(Z), np.log(184.15 * Z ** (-1 / 3)))
            Lp = {1: 6.144, 2: 5.621, 3: 5.805, 4: 5.924}.get(int(Z), np.log(1194.0 * Z ** (-2 / 3)))
            inv += w * 4 * ALPHA * RE ** 2 * NA / A * (Z ** 2 * (Lr - f) + Z * Lp)
        return 1.0 / inv

    # -------------------------------------------------------------- stopping
    def S_col(self, T, positron=False):
        """Collision stopping power [MeV cm2/g] (ICRU 37 eq. 2.4 = ESTAR)."""
        T = np.asarray(T, float)
        tau = T / ME
        g = tau + 1.0
        b2 = 1.0 - 1.0 / g ** 2
        if positron:
            y = tau + 2.0
            F = 2 * np.log(2) - b2 / 12 * (23 + 14 / y + 10 / y ** 2 + 4 / y ** 3)
        else:
            F = 1 - b2 + (tau ** 2 / 8 - (2 * tau + 1) * np.log(2)) / (tau + 1) ** 2
        x = np.log10(np.sqrt(np.clip(g ** 2 - 1, 1e-30, None)))
        d = self.delta(x) if self.dens else 0.0
        L = np.log(tau ** 2 * (tau + 2) / (2 * (self.I / ME) ** 2)) + F - d
        return 0.153537 * self.ZA / b2 * np.clip(L, 1e-3, None)

    def brem_dsdk(self, T, k):
        """Bremsstrahlung d(sigma)/dk per gram [cm2/g/MeV], T,k in MeV.
        Bethe-Heitler + Thomas-Fermi screening (Butcher-Messel/EGS4),
        no Coulomb correction (EGS4 applies it only above 50 MeV)."""
        T = np.asarray(T, float)
        k = np.asarray(k, float)
        E = T + ME
        Ep = E - k
        v = Ep / E
        out = np.zeros(np.broadcast(T, k).shape)
        for w, Z, A in zip(self.w, self.Z, self.A):
            xi = np.log(1194 * Z ** (-2 / 3)) / np.log(184.15 * Z ** (-1 / 3)) if Z > 4 else 1.2
            dl = 136.0 * ME * Z ** (-1 / 3) * k / (E * np.clip(Ep, 1e-12, None))
            p1 = np.where(dl <= 1, 20.867 - 3.242 * dl + 0.625 * dl ** 2, 21.12 - 4.184 * np.log(dl + 0.952))
            p2 = np.where(dl <= 1, 20.209 - 1.930 * dl - 0.086 * dl ** 2, p1)
            lz = 4.0 / 3.0 * np.log(Z)
            br = (1 + v ** 2) * (p1 - lz) - 2.0 / 3.0 * v * (p2 - lz)
            out = out + w * NA / A * ALPHA * RE ** 2 * Z * (Z + xi) * np.clip(br, 0, None) / k
        return np.where((k > 0) & (k < T), out, 0.0)

    def S_rad(self, T, n=200):
        T = np.atleast_1d(np.asarray(T, float))
        u = (np.arange(n) + 0.5) / n                    # k = T*u (midpoint)
        k = T[:, None] * u[None, :]
        return np.sum(k * self.brem_dsdk(T[:, None], k), axis=1) * T / n

    def csda_range(self, T, positron=False):
        """CSDA range [g/cm2] (integral of 1/S_tot from 1 keV; R(1 keV)~0)."""
        T = np.atleast_1d(np.asarray(T, float))
        out = []
        for t in T:
            e = np.geomspace(1e-3, t, 400)
            s = self.S_col(e, positron) + self.S_rad(e)
            out.append(np.trapezoid(1 / s, e))
        return np.array(out)

    # ---------------------------------------------------------------- photons
    def mu_photo(self, E):
        return sum(w * _photo_elem(el, E) for w, el in zip(self.w, self.els))

    def mu_incoh(self, E):
        return self.ZA * NA * sigma_kn(E)

    def mu_pair(self, E):
        E = np.atleast_1d(np.asarray(E, float))
        out = np.zeros_like(E)
        for i, k in enumerate(E):
            if k <= 2 * ME * 1.0001:
                continue
            ep = np.linspace(ME, k - ME, 202)[1:-1]
            em = k - ep
            s = 0.0
            for w, Z, A in zip(self.w, self.Z, self.A):
                xi = np.log(1194 * Z ** (-2 / 3)) / np.log(184.15 * Z ** (-1 / 3)) if Z > 4 else 1.2
                # electron-field (triplet) part has a 4 m_e threshold
                xi_eff = xi * np.clip((k - 4 * ME) / (k - 2 * ME), 0, 1) if k > 4 * ME else 0.0
                dl = 136.0 * ME * Z ** (-1 / 3) * k / (ep * em)
                p1 = np.where(dl <= 1, 20.867 - 3.242 * dl + 0.625 * dl ** 2, 21.12 - 4.184 * np.log(dl + 0.952))
                p2 = np.where(dl <= 1, 20.209 - 1.930 * dl - 0.086 * dl ** 2, p1)
                lz = 4.0 / 3.0 * np.log(Z)
                br = (ep ** 2 + em ** 2) * (p1 - lz) + 2.0 / 3.0 * ep * em * (p2 - lz)
                ds = ALPHA * RE ** 2 * Z * (Z + xi_eff) / k ** 3 * np.clip(br, 0, None)
                s += w * NA / A * np.trapezoid(ds, ep) * pair_coulomb_corr(k, Z)
            out[i] = s
        return out

    def mu_total(self, E):
        return self.mu_photo(E) + self.mu_incoh(E) + self.mu_pair(E)

    def ann_inflight(self, T):
        """Macroscopic in-flight annihilation cross-section per gram [cm2/g]."""
        return self.ZA * NA * sigma_heitler(T)


def pair_coulomb_corr(k, Z):
    """Empirical Coulomb correction to the Born (Bethe-Heitler) pair
    cross-section. The exact (Davies-Bethe-Maximon / Overbo) Coulomb
    correction lowers sigma at high energy (-9 % for Pb asymptotically) and
    raises it strongly near threshold for high Z. Both effects scale ~(alpha Z)^2.
    Form: a_inf + b/(k-2m)^1.8, with (a_inf, b) fitted to XCOM Pb totals
    3-20 MeV [BK] and scaled by (alpha Z / alpha 82)^2. Residuals vs XCOM are
    printed by the self-test (<=4 % for Pb/Fe/water at 3-20 MeV)."""
    s = (Z / 82.0) ** 2
    return (1.0 - 0.13 * s) + 2.4 * s / max(k - 2 * ME, 0.05) ** 1.8


def sigma_kn(E):
    """Klein-Nishina total cross-section per electron [cm2]."""
    k = np.asarray(E, float) / ME
    t1 = (1 + k) / k ** 2 * (2 * (1 + k) / (1 + 2 * k) - np.log(1 + 2 * k) / k)
    t2 = np.log(1 + 2 * k) / (2 * k) - (1 + 3 * k) / (1 + 2 * k) ** 2
    return 2 * np.pi * RE ** 2 * (t1 + t2)


def sigma_heitler(T):
    """Heitler 2-photon annihilation-in-flight cross-section per electron [cm2]."""
    g = np.asarray(T, float) / ME + 1.0
    g = np.clip(g, 1.0 + 1e-9, None)
    s = np.sqrt(g ** 2 - 1)
    return np.pi * RE ** 2 / (g + 1) * ((g ** 2 + 4 * g + 1) / (g ** 2 - 1) * np.log(g + s) - (g + 3) / s)


