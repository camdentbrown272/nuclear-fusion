def _photo_elem(sym, E):
    """Photoabsorption mu/rho [cm2/g] of element `sym` at E [MeV] (Elam)."""
    if sym == 'D':      # same electronic structure as H, per gram scaled by A
        return _photo_elem('H', E) * ELEMENTS['H'][1] / ELEMENTS['D'][1]
    tab = np.asarray(ELAM_PHOTO[sym])
    le = np.log(PHOTO_E_KEV / 1000.0)
    lt = np.log(tab)
    E = np.atleast_1d(np.asarray(E, float))
    lE = np.log(np.clip(E, 1e-3, None))
    out = np.interp(lE, le, lt)
    # extrapolate above 800 keV with last-interval slope, bounded between
    # -2.5 and -1 (Sauter high-energy limit ~1/E)
    slope = (lt[-1] - lt[-2]) / (le[-1] - le[-2])
    slope = min(max(slope, -2.5), -1.0)
    hi = lE > le[-1]
    out[hi] = lt[-1] + slope * (lE[hi] - le[-1])
    lo = lE < le[0]
    out[lo] = lt[0] - 3.0 * (lE[lo] - le[0])
    return np.exp(out)


