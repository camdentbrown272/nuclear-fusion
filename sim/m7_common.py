def critical_energy(mat):
    """Rossi definition: E such that S_col(E) * X0 = E."""
    T = np.geomspace(1, 200, 2000)
    f = mat.S_col(T) * mat.X0 - (T + ME)
    i = np.where(np.diff(np.sign(f)))[0][0]
    return T[i]


def self_test(out=print):
    out("== m7_common self-test (model vs [BK] reference) ==")
    w = MATERIALS['H2O']
    for T, (sc, sr, r) in ESTAR_WATER_BK.items():
        out(f"water T={T:5.1f} MeV  S_col {w.S_col(T):.4f} (ESTAR {sc})  S_rad {w.S_rad(T)[0]:.4f} (ESTAR {sr})"
            f"  CSDA {w.csda_range(T)[0]:.4f} (ESTAR {r}) g/cm2")
    for k, m in MATERIALS.items():
        if m is None or m.x0_ref is None:
            continue
        out(f"X0 {k:6s} Tsai {m.X0:6.2f}  PDG {m.x0_ref:6.2f} g/cm2  ({100*(m.X0/m.x0_ref-1):+.1f} %)")
    for k, ec in PDG_EC_BK.items():
        m = MATERIALS[k]
        out(f"E_c {k:5s} model {critical_energy(m):6.2f}  PDG {ec:6.2f} MeV")
    for k, tab in XCOM_TOTAL_BK.items():
        m = MATERIALS[k]
        for E, v in tab.items():
            mt = m.mu_total(E)[0]
            out(f"mu/rho {k:4s} {E:5.2f} MeV model {mt:.4f} (photo {m.mu_photo(E)[0]:.4f} incoh {m.mu_incoh(E):.4f}"
                f" pair {m.mu_pair(E)[0]:.4f})  XCOM {v:.4f}  ({100*(mt/v-1):+.1f} %)")


if __name__ == '__main__':
    self_test()
